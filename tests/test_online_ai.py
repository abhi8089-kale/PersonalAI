def test_connection_failure_shows_honest_error():
    """Verifies that connection failure shows honest status and does not pretend online mode."""
    mock_client = MagicMock()
    mock_client.chat.completions.create.side_effect = Exception("401 Unauthorized: Invalid API key")

    with patch.dict("os.environ", {"OPENAI_API_KEY": "sk-invalid-key"}), \
         patch("services.llm_service.get_openai_client", return_value=mock_client):

        res = service_test_connection()
        assert res["success"] is False
        assert "Authentication Error" in res["error"]

        status = get_connection_status()
        assert status["mode"] == "Online AI Error"
        assert "AI Connection Error" in status["badge_label"]
        assert status["verified"] is False
        assert "Authentication Error" in status["error"]


def test_agent_tool_calling_executes_in_online_mode(temp_db):
    """
    Verifies that during an online agent turn, tool calls generated by the LLM
    actually execute real Python functions and persist real data in SQLite.
    """
    # Turn 1: LLM requests tool call create_task
    tool_call_resp = {
        "content": "",
        "tool_calls": [
            {
                "id": "call_task_1",
                "type": "function",
                "function": {
                    "name": "create_task",
                    "arguments": '{"title": "Online Agent Task", "priority": "High", "category": "Study"}',
                },
            }
        ],
        "model": "gpt-4o-mini",
        "finish_reason": "tool_calls",
    }

    # Turn 2: LLM summarizes the completed action
    final_resp = {
        "content": "I have created the task 'Online Agent Task' for you in the database.",
        "tool_calls": [],
        "model": "gpt-4o-mini",
        "finish_reason": "stop",
    }

    with patch("agent.orchestrator.is_llm_available", return_value=True), \
         patch("agent.orchestrator.chat_completion", side_effect=[tool_call_resp, final_resp]):

        turn_result = run_agent_turn(
            user_input="Please add a task to study OS",
            db_path=temp_db,
        )

    assert turn_result["tool_executed"] is True
    assert "Online Agent Task" in turn_result["response"]

    # Verify task actually exists in SQLite
    tasks = list_tasks(db_path=temp_db)
    assert len(tasks) == 1
    assert tasks[0]["title"] == "Online Agent Task"
    assert tasks[0]["priority"] == "High"


def test_api_keys_never_exposed():
    """Verifies that API keys are never exposed in error sanitization, masking, or status."""
    secret_key = "sk-super-secret-test-key-12345"
    raw_error = Exception(f"Failed to authenticate with key {secret_key}")

    sanitized = sanitize_error_message(raw_error, api_key=secret_key)
    assert secret_key not in sanitized

    masked = mask_api_key(secret_key)
    assert secret_key not in masked
    assert "••••••••" in masked

    with patch.dict("os.environ", {"OPENAI_API_KEY": secret_key}):
        status = get_connection_status()
        assert secret_key not in status["masked_key"]


def test_empty_environ_precedence_over_dotenv():
    """
    Verifies that an explicitly set empty environment variable
    takes precedence over any value present in the .env file.
    """
    with patch.dict("os.environ", {"OPENAI_API_KEY": ""}):
        assert is_api_key_configured() is False
        from services.llm_service import is_llm_available
        assert is_llm_available() is False

    with patch.dict("os.environ", {"OPENAI_API_KEY": "   "}):
        assert is_api_key_configured() is False
        assert is_llm_available() is False


def test_online_api_error_falls_back_to_local_tool_execution(temp_db):
    """
    Verifies that if an online API error occurs (e.g. 404 or connection error),
    actionable offline commands still execute locally rather than failing completely,
    while keeping the online failure visible in the response.
    """
    with patch("agent.orchestrator.is_llm_available", return_value=True), \
         patch("agent.orchestrator.chat_completion", side_effect=LLMServiceError("Model 'non-existent' not found (404)")):

        result = run_agent_turn(
            user_input="Create task: Study Operating Systems Deadlocks",
            db_path=temp_db,
        )

    assert result["tool_executed"] is True
    assert "Online AI Connection Error" in result["response"]
    assert "Created task" in result["response"]

    tasks = list_tasks(db_path=temp_db)
    assert len(tasks) == 1
    assert "Deadlocks" in tasks[0]["title"]


def test_explicit_offline_mode_flag(temp_db):
    """Verifies that setting offline=True forces local dispatcher even if LLM is online."""
    with patch("agent.orchestrator.is_llm_available", return_value=True):
        result = run_agent_turn(
            user_input="What should I do next?",
            db_path=temp_db,
            offline=True,
        )

    assert result["logs"]["mode"] == "OfflineRuleDispatcher"
    assert result["tool_executed"] is True


def test_provider_inference_and_default_models():
    """Tests provider auto-detection and default model matching."""
    assert infer_provider(None) == "OpenAI"
    assert infer_provider("") == "OpenAI"
    assert infer_provider("https://api.groq.com/openai/v1") == "Groq"
    assert infer_provider("https://generativelanguage.googleapis.com/v1beta/openai/") == "Google Gemini (OpenAI Endpoint)"
    assert infer_provider("http://localhost:11434/v1") == "Ollama (Local)"

    assert get_default_model_for_provider("OpenAI") == "gpt-4o-mini"
    assert get_default_model_for_provider("Groq") == "llama-3.3-70b-versatile"
    assert get_default_model_for_provider("Google Gemini (OpenAI Endpoint)") == "gemini-2.5-flash"
    assert get_default_model_for_provider("Ollama (Local)") == "llama3.1"

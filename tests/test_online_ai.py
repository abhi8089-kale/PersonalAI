"""
Automated tests for Online AI Mode:
- Missing API key activates Offline Mode
- Valid configuration attempts connection
- Successful responses from configured model
- Connection failures show honest status and useful error
- Agent tool calls execute existing application functions in Online Mode
- API keys never appear in logs, exceptions, or UI
- Provider inference and preset resolution
"""

from unittest.mock import MagicMock, patch
import pytest
from services.llm_service import (
    is_api_key_configured,
    get_connection_status,
    test_connection as service_test_connection,
    chat_completion,
    sanitize_error_message,
    mask_api_key,
    infer_provider,
    get_default_model_for_provider,
    LLMServiceError,
)
from agent.orchestrator import run_agent_turn
from services.task_service import list_tasks


def test_missing_api_key_activates_offline_mode():
    """Verifies that when no API key is set, the system honestly reports Offline Mode."""
    with patch.dict("os.environ", {"OPENAI_API_KEY": "", "OPENAI_BASE_URL": ""}):
        assert is_api_key_configured() is False
        status = get_connection_status()
        assert status["mode"] == "Offline Mode"
        assert "Offline Mode Active" in status["badge_label"]
        assert status["verified"] is False


def test_valid_configuration_attempts_connection():
    """Verifies that a valid API key configuration attempts an online call."""
    mock_choice = MagicMock()
    mock_choice.message.content = "PersonalAI Online Verified"
    mock_resp = MagicMock()
    mock_resp.choices = [mock_choice]

    mock_client = MagicMock()
    mock_client.chat.completions.create.return_value = mock_resp

    with patch.dict("os.environ", {"OPENAI_API_KEY": "sk-mock-valid-key", "OPENAI_MODEL": "gpt-4o-mini"}), \
         patch("services.llm_service.get_openai_client", return_value=mock_client):

        assert is_api_key_configured() is True
        res = service_test_connection()

        assert res["success"] is True
        assert "Connection verified" in res["message"]
        mock_client.chat.completions.create.assert_called_once()


def test_successful_online_response_updates_status():
    """Verifies that verified connection updates connection status to online mode."""
    mock_choice = MagicMock()
